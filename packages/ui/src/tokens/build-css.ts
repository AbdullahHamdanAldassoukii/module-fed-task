import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fontFamily, palette, radius, spacing } from './tokens';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const block = (selector: string, vars: Record<string, string>) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  --${kebab(k)}: ${v};`)
    .join('\n')}\n}\n`;

const css =
  `/* GENERATED by src/tokens/build-css.ts from src/tokens/tokens.ts — do not edit by hand. */\n` +
  block(':root', { ...palette.light, radius, spacing, fontSans: fontFamily }) +
  block('.dark', { ...palette.dark });

writeFileSync(path.resolve(import.meta.dirname, '../styles/tokens.css'), css);
console.log('wrote src/styles/tokens.css');
